// KostaFit Runner: o'yinni internetsiz ishlashi uchun keshlaydi
const CACHE = 'kostafit-runner-v1';
const FILES = ['game.html', 'favicon.svg', 'game.webmanifest'];

self.addEventListener('install', e => {
  e.waitUntil(caches.open(CACHE).then(c => c.addAll(FILES)).then(() => self.skipWaiting()));
});

self.addEventListener('activate', e => {
  e.waitUntil(caches.keys()
    .then(keys => Promise.all(keys.filter(k => k.startsWith('kostafit-runner-') && k !== CACHE).map(k => caches.delete(k))))
    .then(() => self.clients.claim()));
});

self.addEventListener('fetch', e => {
  const url = new URL(e.request.url);
  if (e.request.method !== 'GET' || url.origin !== location.origin) return;
  if (!FILES.some(f => url.pathname.endsWith('/' + f))) return;
  // Avval tarmoq (yangilanishlar uchun), internet bo'lmasa — keshdan
  e.respondWith(
    fetch(e.request)
      .then(res => { const copy = res.clone(); caches.open(CACHE).then(c => c.put(e.request, copy)); return res; })
      .catch(() => caches.match(e.request, { ignoreSearch: true }))
  );
});
